import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
const browser = await chromium.launch({ executablePath: 'E:/Python项目/toochuangai/outputs/qa-browser-binaries/chromium_headless_shell-1255/chrome-headless-shell-win64/chrome-headless-shell.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 }, reducedMotion:'reduce' });
const errors=[];page.on('pageerror', e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5678/replenishment-demo.html');
await page.getByRole('heading',{name:'智能补货中心 亚马逊'}).waitFor();
assert.equal(await page.locator('tbody tr').count(),10);
assert.equal(await page.locator('.metrics').evaluate(el=>getComputedStyle(el).display),'grid');
assert.equal(await page.locator('.sku-button.ocean').first().evaluate(el=>getComputedStyle(el).color),'rgb(38, 112, 215)');
await page.getByPlaceholder('搜索 SKU / 产品名称').fill('TC-1024');
await page.waitForFunction(()=>document.querySelectorAll('tbody tr').length===1);
assert.equal(await page.locator('tbody tr').count(),1);
await page.getByPlaceholder('搜索 SKU / 产品名称').fill('');
await page.waitForFunction(()=>document.querySelectorAll('tbody tr').length===10);
await page.locator('.sku-button').first().click();
await page.getByRole('heading',{name:'TC-1024',exact:true}).waitFor();
await page.locator('.ant-drawer-close').click();
const qty=page.getByRole('spinbutton',{name:'TC-1024 订货量',exact:true});
await qty.fill('800');await qty.press('Tab');
assert.ok(await page.locator('.pending').isVisible());
await page.getByRole('button',{name:/同步订货量/}).click();
await page.getByRole('checkbox',{name:'选择 TC-1024',exact:true}).check();
await page.getByRole('button',{name:'预览采购计划',exact:true}).click();
await page.getByText('采购计划预览',{exact:true}).waitFor();
assert.match(await page.locator('.plan-summary').innerText(),/800/);
await page.getByRole('button',{name:'继续调整',exact:true}).click();
await page.getByRole('button',{name:'刷新数据',exact:true}).click();
await page.getByText('演示数据已刷新',{exact:true}).waitFor();
await page.getByRole('button',{name:'取消选择',exact:true}).click();
await page.screenshot({path:'replenishment-demo-desktop.png',fullPage:true});
await page.setViewportSize({width:768,height:1024});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
console.log('PASS: render, blue ocean SKU, search, drawer, quantity sync, purchase preview, refresh, responsive width; no runtime errors');
await browser.close();
